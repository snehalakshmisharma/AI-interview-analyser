export type ResponseType = "TEXT" | "AUDIO" | "VIDEO";

export type ResponseSubmission = {
  interviewQuestionId: string;
  responseType: ResponseType;
  textContent?: string | null;
  duration?: number;
};

export function validateResponseSubmission(value: unknown):
  | { success: true; data: ResponseSubmission }
  | { success: false; error: string; status: 400 | 403 } {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return { success: false, error: "Invalid response payload", status: 400 };
  }

  const body = value as Record<string, unknown>;
  const responseType = body.responseType ?? "TEXT";
  if (responseType !== "TEXT" && responseType !== "AUDIO" && responseType !== "VIDEO") {
    return { success: false, error: "Invalid responseType", status: 400 };
  }

  if (responseType !== "TEXT" && (
    "transcript" in body ||
    "transcriptText" in body ||
    (typeof body.textContent === "string" && body.textContent.trim().length > 0)
  )) {
    return { success: false, error: "Media transcripts are generated by the server and cannot be supplied by the client", status: 403 };
  }

  if (typeof body.interviewQuestionId !== "string" || !body.interviewQuestionId) {
    return { success: false, error: "interviewQuestionId is required", status: 400 };
  }
  if (body.textContent != null && typeof body.textContent !== "string") {
    return { success: false, error: "textContent must be a string", status: 400 };
  }
  if (body.duration != null && (typeof body.duration !== "number" || !Number.isFinite(body.duration))) {
    return { success: false, error: "duration must be a number", status: 400 };
  }

  return {
    success: true,
    data: {
      interviewQuestionId: body.interviewQuestionId,
      responseType,
      textContent: body.textContent as string | null | undefined,
      duration: body.duration as number | undefined,
    },
  };
}

export function validateTextResponseEdit(value: unknown):
  | { success: true; textContent: string }
  | { success: false; error: string } {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return { success: false, error: "Invalid response payload" };
  }
  const body = value as Record<string, unknown>;
  const textContent = body.textContent ?? body.transcriptText ?? body.transcript;
  if (typeof textContent !== "string" || textContent.trim().length < 2) {
    return { success: false, error: "Response text is required (minimum 2 characters)" };
  }
  return { success: true, textContent: textContent.trim() };
}

export function validateResponseEdit(value: unknown, responseType: ResponseType, transcriptLocked: boolean):
  | { success: true; textContent: string }
  | { success: false; error: string; status: 400 | 403 } {
  if (responseType !== "TEXT" || transcriptLocked) {
    return {
      success: false,
      error: "Audio/video transcripts are server-generated and cannot be edited. Re-record the response instead.",
      status: 403,
    };
  }
  const result = validateTextResponseEdit(value);
  return result.success ? result : { ...result, status: 400 };
}